#!/bin/bash
# Builds KEMPT.md (the whole kit in one file) and refreshes the README's
# one-line start prompt from kit.json. Run after any change, before a release:
#   bash tools/bundle.sh
set -euo pipefail
cd "$(dirname "$0")/.."

python3 - <<'PY'
import json, re

kit = json.load(open("kit.json"))
home = kit.get("home", "").rstrip("/")
link = home if home else "<link to this kit>"
bundle_url = kit.get("bundle") or (link + "/KEMPT.md")

files = [
    "AGENTS.md", "RECIPE.md", "CHAT-ONLY.md",
    "reference/safety-rules.md", "reference/ideas.md", "reference/known-leaks.md",
    "reference/architecture.md", "reference/menu-bar-app.md", "reference/themes.md",
    "templates/AGENTS.md.template", "templates/picks.example.json",
    "kit.json", "CHANGELOG.md", "NOTICE.md", "LICENSE",
]
optional = []

out = [
    "# KEMPT.md — Kempt %s, in one file" % kit["version"],
    "",
    "This file is the whole Kempt. Each original file follows below its own `===== FILE: <path> =====` line.",
    "",
    "- **If you are an AI coding agent that can run commands on this Mac:** follow the FILE: RECIPE.md section, starting at step 0. Whenever it says to read a file, read that file's section here. Build the user's tool in a new folder; you don't need to save this kit to disk.",
    "- **If you are a chat-only AI** (you cannot run commands): follow the FILE: CHAT-ONLY.md section only.",
    "- Read FILE: NOTICE.md and show the user its first paragraph before you start.",
    "",
    "Kit home: %s" % link,
    "",
]
for f in files + [o for o in optional if __import__("os").path.exists(o)]:
    body = open(f).read().rstrip("\n")
    out += ["", "===== FILE: %s =====" % f, "", body]
open("KEMPT.md", "w").write("\n".join(out) + "\n")

readme = open("README.md").read()
block = ('<!-- start-prompt: generated by tools/bundle.sh from kit.json "home" -->\n```text\n'
         "Read %s and follow it to build me my own computer care tool.\n```\n<!-- /start-prompt -->" % bundle_url)
readme, n = re.subn(r"<!-- start-prompt:.*?<!-- /start-prompt -->", lambda m: block, readme, flags=re.S)
assert n == 1, "start-prompt markers missing from README.md"
open("README.md", "w").write(readme)
print("KEMPT.md: %d lines, kit %s, home %s" % (len(out), kit["version"], link))
PY
